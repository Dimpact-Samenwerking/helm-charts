def test_pymarkdown_not_installed_fails(
    libmarkdowncheck: ModuleType, vp: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    chart_dir = make_chart_dir(tmp_path, files={"README.md": "# a\n"})
