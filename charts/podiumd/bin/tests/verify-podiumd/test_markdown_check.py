def test_a_pymarkdown_crash_is_reported_as_a_failure_not_a_clean_pass(
    libmarkdowncheck: ModuleType,
    vp: ModuleType,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
):
    """Regression: pymarkdown's default scheme returns 1 for findings and real
    failures alike; with --return-code-scheme explicit, anything but 0 or 4 fails."""
    chart_dir = make_chart_dir(tmp_path, files={"docs/foo.md": "# a\n"})
    monkeypatch.setattr(libmarkdowncheck, "find_pymarkdown", lambda chart_dir: "/usr/local/bin/pymarkdown")
    monkeypatch.setattr(
        libmarkdowncheck, "run", lambda cmd, **kw: pymarkdown_result("", returncode=1, stderr="not a valid path")
    )

    ok, detail = vp.check_markdown(chart_dir)
    assert ok is False
    assert "pymarkdown failed" in detail
    assert "not a valid path" in detail


def test_findings_fail_the_check(
    libmarkdowncheck: ModuleType,
    vp: ModuleType,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
):
    chart_dir = make_chart_dir(tmp_path, files={"docs/foo.md": "Not a heading\n"})
    monkeypatch.setattr(libmarkdowncheck, "find_pymarkdown", lambda chart_dir: "/usr/local/bin/pymarkdown")
    finding_line = (
        f"{chart_dir / 'docs' / 'foo.md'}:1:1: MD041: First line in file should be a top level "
        f"heading (first-line-heading,first-line-h1)\n"
    )
    monkeypatch.setattr(libmarkdowncheck, "run", lambda cmd, **kw: pymarkdown_result(finding_line))

    ok, detail = vp.check_markdown(chart_dir)
    assert ok is False
    assert detail == "1 finding(s)"
    out = capsys.readouterr().out
    assert "Found 1 markdown finding(s)" in out
    assert "MD041 (first-line-heading)" in out
    assert "docs/foo.md:1:1  First line in file should be a top level heading" in out


def test_disables_line_length_and_commands_show_output_rules(
    libmarkdowncheck: ModuleType, vp: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    chart_dir = make_chart_dir(tmp_path, files={"docs/foo.md": "# a\n"})
    monkeypatch.setattr(libmarkdowncheck, "find_pymarkdown", lambda chart_dir: "/usr/local/bin/pymarkdown")
    captured = {}

    def fake_run(cmd, **kw):
        captured["cmd"] = cmd
        return pymarkdown_result("", returncode=0)

    monkeypatch.setattr(libmarkdowncheck, "run", fake_run)
    vp.check_markdown(chart_dir)

    cmd = captured["cmd"]
    assert cmd[0] == "/usr/local/bin/pymarkdown"
    assert cmd[1:3] == ["--return-code-scheme", "explicit"]
    assert cmd[3:5] == ["-d", "md013,md014"]
    assert "scan" in cmd
    assert cmd.index("-d") < cmd.index("scan")
    assert str(chart_dir / "docs" / "foo.md") in cmd
    # every file arg comes after "scan"
    assert cmd.index(str(chart_dir / "docs" / "foo.md")) > cmd.index("scan")


def test_md024_scoped_to_siblings_only(
    libmarkdowncheck: ModuleType, vp: ModuleType, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """MD024 only flags duplicates under the same parent: docs repeat
    subsection names under different parents."""
    chart_dir = make_chart_dir(tmp_path, files={"docs/foo.md": "# a\n"})
    monkeypatch.setattr(libmarkdowncheck, "find_pymarkdown", lambda chart_dir: "/usr/local/bin/pymarkdown")
    captured = {}
    monkeypatch.setattr(
        libmarkdowncheck, "run", lambda cmd, **kw: (captured.__setitem__("cmd", cmd), pymarkdown_result("", 0))[1]
    )

    vp.check_markdown(chart_dir)

    cmd = captured["cmd"]
    assert "-s" in cmd
    assert "plugins.md024.siblings_only=$!True" in cmd
    assert cmd.index("-s") < cmd.index("scan")


