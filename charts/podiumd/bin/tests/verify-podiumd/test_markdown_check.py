"""check_markdown: pymarkdown over every *.md under chart_dir; any finding or
a missing pymarkdown fails. `run` is mocked except for find_pymarkdown tests."""

from pathlib import Path
from types import ModuleType
from types import SimpleNamespace

import pytest


def pymarkdown_result(stdout, returncode=4, stderr=""):
    """Default returncode 4: --return-code-scheme explicit's own "findings reported" code."""
    return SimpleNamespace(returncode=returncode, stdout=stdout, stderr=stderr)


def make_chart_dir(tmp_path: Path, files=None, upgrade_docs_baseline=None):
    tmp_path.mkdir(parents=True, exist_ok=True)
    (tmp_path / "Chart.yaml").write_text("name: podiumd\nversion: 4.9.0\n", encoding="utf-8")
    if upgrade_docs_baseline is not None:
        (tmp_path / "etc").mkdir(exist_ok=True)
        (tmp_path / "etc" / "release-baseline.yaml").write_text(
            f'upgrade_docs: "{upgrade_docs_baseline}"\n', encoding="utf-8"
        )
    for rel_path, content in (files or {}).items():
        p = tmp_path / rel_path
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
    return tmp_path


def test_find_markdown_files_excludes_vendored_charts_dir(libmarkdowncheck: ModuleType, tmp_path: Path):
    chart_dir = make_chart_dir(
        tmp_path,
        files={
            "docs/foo.md": "# b\n",
            "charts/some-subchart/README.md": "# c\n",
        },
    )
    found = libmarkdowncheck.find_markdown_files(chart_dir)
    assert found == [chart_dir / "docs" / "foo.md"]


