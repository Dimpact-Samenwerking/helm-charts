"""Run pymarkdown on every in-scope *.md file under chart_dir; fail on any finding.

In scope: generic docs plus docs/_UPGRADE_PATHS/*.md of the current release only
(past releases are frozen).

Disabled: MD013 line-length (tables/links/prose; ~89% of findings) and MD014
commands-show-output (docs show commands without output). MD024 no-duplicate-heading
is siblings_only, since several docs repeat a subsection per parent (e.g. per realm).
"""

import re
import shutil

from pathlib import Path

from lib.chart.release_baseline_basics import chart_version
from lib.chart.release_baseline_basics import upgrade_docs_baseline as read_upgrade_docs_baseline
from lib.gitutil import find_repo_root
from lib.procutil import run
from lib.render_scope import print_grouped_findings
from lib.settings import quality_gates_markdown_disabled_rules
from lib.upgradedoc.doc_names import doc_name_re

# Applied on every invocation (scan and fix); see module docstring for md024.
MARKDOWN_PLUGIN_SETTINGS = ["-s", "plugins.md024.siblings_only=$!True"]


def pymarkdown_rule_args(chart_dir: Path) -> list[str]:
    """pymarkdown's rule options: the disabled rules from settings.yaml and MARKDOWN_PLUGIN_SETTINGS.

    Shared by this check and run_python_checks, which lints bin/*.md that this check skips.
    """
    return ["-d", ",".join(quality_gates_markdown_disabled_rules(chart_dir)), *MARKDOWN_PLUGIN_SETTINGS]


MARKDOWN_FINDING_RE = re.compile(
    r"^(?P<path>.+?):(?P<line>\d+):(?P<col>\d+):\s+"
    r"(?P<rule>MD\d+):\s+(?P<message>.*?)\s*\((?P<aliases>[a-z0-9,-]+)\)\s*$",
    re.MULTILINE,
)


def find_markdown_files(chart_dir: Path):
    """Every *.md file under chart_dir, excluding:
    - charts/ (vendored) and bin/ (release tooling, not part of the chart);
    - README.md, generated by helm-docs;
    - docs/_UPGRADE_PATHS/<baseline>-to-<target>-*.md unless <target> is the current
      chart version and (when release-baseline.yaml has upgrade_docs) <baseline> is
      that baseline: the same key lib.component_docs.baseline_doc_paths uses.
    """
    vendored = chart_dir / "charts"
    bin_dir = chart_dir / "bin"
    readme = chart_dir / "README.md"
    upgrade_paths_dir = chart_dir / "docs" / "_UPGRADE_PATHS"
    current_target = chart_version(chart_dir / "Chart.yaml")
    current_baseline = read_upgrade_docs_baseline(chart_dir)

    def in_scope(p: Path):
        if vendored in p.parents or bin_dir in p.parents or p == readme:
            return False
        if upgrade_paths_dir in p.parents:
            m = doc_name_re().fullmatch(p.name)
            if m:
                if m.group("target") != current_target:
                    return False
                if current_baseline is not None and m.group("baseline") != current_baseline:
                    return False
        return True

    return sorted(p for p in chart_dir.rglob("*.md") if in_scope(p))


def find_pymarkdown(chart_dir: Path):
    """<repo-root>/.venv/bin/pymarkdown if it exists, else pymarkdown on PATH, else None."""
    repo_root = find_repo_root(chart_dir)
    if repo_root is not None:
        venv_bin = repo_root / ".venv" / "bin" / "pymarkdown"
        if venv_bin.is_file():
            return str(venv_bin)
    return shutil.which("pymarkdown")


def _relative_path(path_str: str, base_dir: Path):
    try:
        return str(Path(path_str).relative_to(base_dir))
    except ValueError:
        return path_str


def check_markdown(chart_dir: Path):
    """Lint in-scope *.md files with pymarkdown; fail on any finding or a missing install.

    Uses --return-code-scheme explicit: 0 = clean, 4 = findings, anything else is a
    pymarkdown failure.
    """
    pymarkdown = find_pymarkdown(chart_dir)
    if pymarkdown is None:
        return False, (
            "pymarkdown is not installed (see README-release-process.md#setup, or --skip=markdown to bypass)"
        )

    files = find_markdown_files(chart_dir)
    if not files:
        print("OK: no markdown files found")
        return True, "no markdown files"

    result = run(
        [
            pymarkdown,
            "--return-code-scheme",
            "explicit",
            *pymarkdown_rule_args(chart_dir),
            "scan",
            *[str(f) for f in files],
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode not in (0, 4):
        return False, f"pymarkdown failed (exit {result.returncode}): {result.stderr.strip() or result.stdout.strip()}"
    output = result.stdout + result.stderr

    findings: list[dict[str, str]] = []
    for m in MARKDOWN_FINDING_RE.finditer(output):
        d = m.groupdict()
        d["path"] = _relative_path(d["path"], chart_dir)
        findings.append(d)

    if findings:
        print(f"Found {len(findings)} markdown finding(s) across {len(files)} file(s):")
        print_grouped_findings(
            findings,
            key_fn=lambda f: (f["rule"], f["aliases"].split(",")[0]),
            item_fn=lambda f: f"{f['path']}:{f['line']}:{f['col']}  {f['message']}",
            label_fn=lambda k: f"{k[0]} ({k[1]})",
            items_label="location(s)",
        )
    else:
        print(f"OK: no markdown findings across {len(files)} file(s)")

    return not findings, f"{len(findings)} finding(s)"
